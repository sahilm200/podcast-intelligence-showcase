"""Email notification system for P³."""

import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from email.mime.base import MIMEBase
from email import encoders
from datetime import datetime, date
from typing import List, Dict, Any, Optional
from pathlib import Path
import os


class DigestEmailer:
    def __init__(self, config: Dict[str, Any]):
        """Initialize emailer with configuration."""
        self.enabled = config.get('enabled', False)
        self.smtp_server = config.get('smtp_server', 'smtp.gmail.com')
        self.smtp_port = config.get('smtp_port', 587)
        self.sender_email = config.get('sender_email', '')
        self.sender_password = config.get('sender_password', '')
        self.recipient_email = config.get('recipient_email', '')

    def send_digest(self, digest_date: date, summary_count: int,
                   markdown_file: Optional[Path] = None,
                   json_file: Optional[Path] = None) -> bool:
        """Send digest email with optional attachments.

        Args:
            digest_date: Date of the digest
            summary_count: Number of episodes processed
            markdown_file: Path to markdown export (optional)
            json_file: Path to JSON export (optional)

        Returns:
            True if email sent successfully, False otherwise
        """
        if not self.enabled:
            print("Email notifications disabled in config")
            return False

        if not self._validate_config():
            print("Email configuration incomplete. Check config/feeds.yaml")
            return False

        try:
            # Create message
            msg = MIMEMultipart()
            msg['From'] = self.sender_email
            msg['To'] = self.recipient_email
            msg['Subject'] = f'P³ Podcast Digest - {digest_date}'

            # Create email body
            body = self._create_email_body(digest_date, summary_count)
            msg.attach(MIMEText(body, 'plain'))

            # Attach files if provided
            if markdown_file and markdown_file.exists():
                self._attach_file(msg, markdown_file)
            if json_file and json_file.exists():
                self._attach_file(msg, json_file)

            # Send email
            server = smtplib.SMTP(self.smtp_server, self.smtp_port)
            server.starttls()
            server.login(self.sender_email, self.sender_password)
            server.send_message(msg)
            server.quit()

            print(f"✓ Email sent successfully to {self.recipient_email}")
            return True

        except Exception as e:
            print(f"✗ Failed to send email: {e}")
            return False

    def _validate_config(self) -> bool:
        """Validate email configuration."""
        required = ['sender_email', 'sender_password', 'recipient_email']
        return all(getattr(self, field) for field in required)

    def _create_email_body(self, digest_date: date, summary_count: int) -> str:
        """Create email body text."""
        return f"""
Parakeet Podcast Processor (P³)
Automated Digest Report

Date: {digest_date}
Episodes Processed: {summary_count}

Your podcast digest has been generated and is attached to this email.

Summary:
- {summary_count} podcast episodes analyzed
- Full summaries, key topics, themes, and quotes extracted
- Notable companies and startups identified
- Actionable insights and takeaways extracted

Files Attached:
- Markdown digest (for easy reading)
- JSON export (for data analysis)

---
Generated by P³ - Parakeet Podcast Processor
Inspired by Tomasz Tunguz's podcast analysis system
"""

    def _attach_file(self, msg: MIMEMultipart, file_path: Path):
        """Attach file to email message."""
        with open(file_path, 'rb') as f:
            part = MIMEBase('application', 'octet-stream')
            part.set_payload(f.read())
            encoders.encode_base64(part)
            part.add_header(
                'Content-Disposition',
                f'attachment; filename= {file_path.name}'
            )
            msg.attach(part)

